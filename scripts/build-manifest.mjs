/* One manifest over whatever decks happen to be in public/decks, so each
   builder only has to write its own file and the app has one thing to fetch.

   node scripts/build-manifest.mjs
*/
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';

const DIR = 'public/decks';
if (!existsSync(DIR)) { console.error('no public/decks yet'); process.exit(2); }

const decks = [];
for (const f of readdirSync(DIR)) {
  if (!f.endsWith('.json') || f === 'manifest.json') continue;
  const d = JSON.parse(readFileSync(`${DIR}/${f}`, 'utf8'));
  decks.push({ id: d.id, name: d.name, style: d.style, area: d.area, source: d.source, count: d.cards.length, file: `decks/${f}` });
}
decks.sort((a, b) => a.area.localeCompare(b.area) || a.name.localeCompare(b.name));

writeFileSync(`${DIR}/manifest.json`, JSON.stringify({
  note: 'Generated by scripts/build-manifest.mjs',
  attribution: {
    otdb: 'Open Trivia Database, CC BY-SA 4.0 — https://opentdb.com/',
    table: 'Reference tables, public domain facts',
    house: 'Written for this deck',
  },
  decks,
}, null, 1));

const total = decks.reduce((n, d) => n + d.count, 0);
console.log(`manifest: ${decks.length} decks, ${total} cards`);
for (const area of [...new Set(decks.map(d => d.area))]) {
  const inArea = decks.filter(d => d.area === area);
  console.log(`  ${area}: ${inArea.length} decks, ${inArea.reduce((n, d) => n + d.count, 0)} cards`);
}
